function slug(s: string) {
  return s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

export const vocabBank: VocabItem[] = (Object.keys(raw) as Exclude<VocabTheme, 'eigen'>[]).flatMap((theme) =>
  raw[theme].items.map((line) => {
    const [nl, es, ex] = line.split('|').map((p) => p.trim());
    return { id: `${theme}:${slug(nl)}`, nl, es, ex, theme, level: raw[theme].level };
  }),
);
